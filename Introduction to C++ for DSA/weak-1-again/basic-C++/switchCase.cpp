#include <bits/stdc++.h>
using namespace std;
int main()
{
    int x;
    // cin >> x;
    while (cin >> x)
    {
        switch (x)
        {
        case 1:
            cout << "one"<<endl;
            break;
        case 2:
            cout << "two"<<endl;
            break;

        case 3:
            cout << "three"<<endl;
            break;
        case 4:
            cout << "four"<<endl;
            break;
        case 5:
            cout << "five"<<endl;
            break;

        default:
            cout << "Invalid input"<<endl;
        }
    }
    return 0;
}